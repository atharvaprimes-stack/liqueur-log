export type AppLanguage = 'en' | 'mr';

function publishTranslations(): void {
  i18n.addResourceBundle('en', 'translation', resources.en.translation, true, true);
  i18n.addResourceBundle('mr', 'translation', resources.mr.translation, true, true);
}

if (!i18n.isInitialized) {
  i18n.use(initReactI18next);
  void i18n.init({
    resources,
    lng: 'en',
    fallbackLng: 'en',
    interpolation: { escapeValue: false },
  });
} else {
  publishTranslations();
}

export function isAppLanguage(value: string | null | undefined): value is AppLanguage {
  return value === 'en' || value === 'mr';
}

export default i18n;
